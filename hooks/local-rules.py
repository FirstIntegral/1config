#!/usr/bin/env python3
"""local-rules.py — put this machine's local.json overrides where each tool reads rules.

    python3 ~/.agents/hooks/local-rules.py apply    # setup.sh runs this
    python3 ~/.agents/hooks/local-rules.py check    # verify.sh runs this

The canonical AGENTS.md is a tracked file that all four tools load through a
symlink, so it cannot carry a per-machine value. local.json can. This script
turns the `caveman` key (off, lite, or ultra) into one small generated rule per
tool, in the place that tool always loads:

    Claude Code   ~/.claude/rules/1config-local.md
    Grok          ~/.grok/rules/1config-local.md
    Cursor Code   ~/.cursor/rules/1config-local.mdc      (alwaysApply)
    OpenCode      ~/.config/opencode/1config-local.md    (listed in "instructions")

No `caveman` key, the value `full`, or no local.json at all removes those four
again. `check` exits 1 when what is installed differs from what local.json asks
for. --home and --local-json are for verify.sh only.
"""
import argparse
import json
import pathlib
import sys

LEVELS = {
    "off": (
        "Write normal prose: full sentences, articles, no caveman style. "
        "Code, commits, and PRs were already normal."
    ),
    "lite": (
        "Level lite: drop filler, pleasantries, and hedging. Keep articles and full sentences."
    ),
    "ultra": (
        "Level ultra: maximum compression. Abbreviations and arrows (X → Y) are fine. "
        "Never drop not, never, no, or only."
    ),
}
OC_ENTRY = "~/.config/opencode/1config-local.md"


def body(level):
    return (
        "# 1config local override\n\n"
        "Generated by `~/.agents/setup.sh` from `~/.agents/local.json`. Do not edit this file.\n\n"
        f"Caveman level on this machine: **{level}**. This replaces the level in "
        '"Caveman mode — ALWAYS ON" in the global rules.\n\n'
        f"{LEVELS[level]}\n"
    )


def cursor_body(level):
    return (
        "---\n"
        "description: 1config local override (generated — edit ~/.agents/local.json)\n"
        "alwaysApply: true\n"
        "---\n\n" + body(level)
    )


def load_jsonc(text):
    """JSON with // and /* */ comments and trailing commas."""
    out, i, n, in_string, escaped = [], 0, len(text), False, False
    while i < n:
        c = text[i]
        if in_string:
            out.append(c)
            if escaped:
                escaped = False
            elif c == "\\":
                escaped = True
            elif c == '"':
                in_string = False
            i += 1
        elif c == '"':
            in_string = True
            out.append(c)
            i += 1
        elif text.startswith("//", i):
            j = text.find("\n", i)
            i = n if j == -1 else j
        elif text.startswith("/*", i):
            j = text.find("*/", i)
            i = n if j == -1 else j + 2
        elif c == ",":
            j = i + 1
            while j < n and text[j].isspace():
                j += 1
            if j < n and text[j] in "}]":
                i += 1
            else:
                out.append(c)
                i += 1
        else:
            out.append(c)
            i += 1
    return json.loads("".join(out))


def wanted_level(local_json):
    if not local_json.is_file():
        return None
    try:
        value = json.loads(local_json.read_text()).get("caveman")
    except (ValueError, AttributeError):
        return None
    return value if value in LEVELS else None


def targets(home):
    return {
        "claude": (home / ".claude/rules/1config-local.md", body),
        "grok": (home / ".grok/rules/1config-local.md", body),
        "cursor": (home / ".cursor/rules/1config-local.mdc", cursor_body),
        "opencode": (home / ".config/opencode/1config-local.md", body),
    }


def opencode_entry_present(cfg_path):
    if not cfg_path.is_file():
        return False, None
    cfg = load_jsonc(cfg_path.read_text())
    entries = cfg.get("instructions")
    return isinstance(entries, list) and OC_ENTRY in entries, cfg


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("mode", choices=["apply", "check"])
    ap.add_argument("--home", default=str(pathlib.Path.home()))
    ap.add_argument("--local-json", default=None)
    args = ap.parse_args()

    home = pathlib.Path(args.home)
    local_json = pathlib.Path(args.local_json) if args.local_json else home / ".agents/local.json"
    level = wanted_level(local_json)
    oc_cfg = home / ".config/opencode/opencode.jsonc"
    problems = []
    changed = []

    for tool, (path, render) in targets(home).items():
        want = render(level) if level else None
        have = path.read_text() if path.is_file() else None
        if want == have:
            continue
        if args.mode == "check":
            problems.append(f"{tool}: {path} " + ("is stale or missing" if want else "should not exist"))
        elif want is None:
            path.unlink()
            changed.append(f"removed {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(want)
            changed.append(f"wrote {path}")

    present, cfg = opencode_entry_present(oc_cfg)
    if bool(level) != present:
        if args.mode == "check":
            problems.append(
                "opencode: instructions " + ("lacks" if level else "still lists") + f" {OC_ENTRY}"
            )
        elif level:
            cfg = cfg if cfg is not None else {"$schema": "https://opencode.ai/config.json"}
            entries = cfg.get("instructions")
            entries = entries if isinstance(entries, list) else []
            entries.append(OC_ENTRY)
            cfg["instructions"] = entries
            oc_cfg.parent.mkdir(parents=True, exist_ok=True)
            oc_cfg.write_text(json.dumps(cfg, indent=2) + "\n")
            changed.append(f"listed {OC_ENTRY} in {oc_cfg}")
        else:
            cfg["instructions"] = [e for e in cfg["instructions"] if e != OC_ENTRY]
            if not cfg["instructions"]:
                del cfg["instructions"]
            oc_cfg.write_text(json.dumps(cfg, indent=2) + "\n")
            changed.append(f"unlisted {OC_ENTRY} in {oc_cfg}")

    if args.mode == "check":
        for p in problems:
            print(p)
        if not problems:
            print(f"caveman override: {level}" if level else "no local override (caveman full)")
        return 1 if problems else 0
    for c in changed:
        print("  " + c)
    if not changed:
        print("  ok       " + (f"caveman override {level} already in place" if level else "no local override (caveman full)"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
